"""W75 through the real dock, CPU engine, Bidah 03's ground (W27's and W73's set-up).

1. A diversion point's method and parameters through the Basin points box's table, a source on the same junction with
   and without an area, generated by the real engine; a run on the generated basin with the diversion.
2. A flow line's Enters moving and Flows to columns; W61's Bidah job run twice, momentum off (W61's water at rest) and
   on (W70's default): the pile against the domain edge re-measured.
3. An HMS basin's reservoirs, read only, with the engine's words: W68's copy of his project, and a copy of it the
   engine refuses.
"""

import json

THRESHOLD_KM2 = 2.0
RATE_M3S = 5.0
VOLUME_M3 = 9000.0
AREA_KM2 = 3.0
PILE = (439416.0, 2728690.0)
"""Where W61's run left 4.3 m against the domain edge."""
NEAR_M = 100.0


def by_kind(model, kind):
    return [e for e in model["elements"] if e["kind"] == kind]


def value(element, key):
    return element["parameters"][key]["value"]


def max_depth_near(folder, points, radius):
    """The deepest cell of the run's max_depth map within ``radius`` of any of the points, and where."""
    import numpy as np
    from osgeo import gdal

    ds = gdal.Open(str(folder / "maps" / "max_depth.tif"))
    x0, dx, _, y0, _, dy = ds.GetGeoTransform()
    band = ds.GetRasterBand(1)
    data = band.ReadAsArray().astype(float)
    nodata = band.GetNoDataValue()
    if nodata is not None:
        data[data == nodata] = np.nan
    ys, xs = np.mgrid[0 : data.shape[0], 0 : data.shape[1]]
    cx, cy = x0 + (xs + 0.5) * dx, y0 + (ys + 0.5) * dy
    near = np.zeros(data.shape, bool)
    for px, py in points:
        near |= (cx - px) ** 2 + (cy - py) ** 2 <= radius**2
    picked = np.where(near & np.isfinite(data), data, -1.0)
    k = np.unravel_index(int(np.argmax(picked)), picked.shape)
    return float(picked[k]), (float(cx[k]), float(cy[k]))


def scenario(h):
    import csv
    import importlib.util
    from pathlib import Path

    from qgis.core import QgsPointXY, QgsProject
    from qgis.PyQt.QtCore import QCoreApplication, Qt

    h.VENV = Path(r"D:\Mojtaba\Renardet\Wadi2D\.venv\Scripts\python.exe")  # a worktree has no venv of its own
    h.TOTAL_LIMIT = 3600.0
    ground = h.Bidah()
    dam = json.loads((h.VALIDATION / "jobs" / "dam_Bidah03_100yr_20.json").read_text(encoding="utf-8"))
    crests = [o for o in dam["terrain"]["objects"] if o["kind"] == "crest_line"]
    longest = max(crests, key=lambda o: len(o["coordinates"]))
    crest = h.add_vector(
        h.geojson("crest", [h.line(o["coordinates"], z=o["z_constant"], name="Bidah 03" if o is longest else f"saddle {n}")
                            for n, o in enumerate(crests, 1)]),
        "crest", ground.crs,
    )  # fmt: skip
    dock = yield from h.open_dock()
    hy, box, s, b = dock.hydrology, dock.hydrology.basin, dock.structures, dock.boundaries
    h.set_rain_job(dock, ground, "wiring", dx=20.0, rain=60.0, hours=1.0, sim_hours=1.0, pixels=False)
    dock.panel.backend.setCurrentIndex(dock.panel.backend.findData("cpu"))
    s.layers["crest_line"].setLayer(crest)
    s.fields["crest_line"]["crest_z"].setField("z")
    box.setChecked(True)
    box.threshold.setValue(THRESHOLD_KM2)

    def generate():
        old = box.model
        box.generate_button.click()
        yield lambda: box.generate_button.isEnabled()
        h.log(f"summary: {box.summary.text()[:400]}")
        return box.model if box.model is not old else None

    def click(kind, x, y):
        box.point_kind.setCurrentIndex(box.point_kind.findData(kind))
        box.place_button.setChecked(True)
        QCoreApplication.processEvents()
        dock.basin_points.tool.canvasClicked.emit(QgsPointXY(x, y), Qt.LeftButton)
        QCoreApplication.processEvents()

    def cell(row, column, text):
        box.diversions.item(row, column).setText(text)  # as a user types into the cell
        QCoreApplication.processEvents()

    h.log("=== 1 a diversion point through the box's table, a source on its junction")
    plain = yield from generate()
    h.check("a plain basin", plain is not None and by_kind(plain, "reservoir"), box.summary.text()[:200])
    reservoir = next(e["name"] for e in by_kind(plain, "junction") if e["downstream"] is None)  # the outlet: below everything
    box.new_points_button.click()
    QCoreApplication.processEvents()
    layer = box.pour.currentLayer()
    h.check("the new layer has the parameters field", "parameters" in layer.fields().names(), layer.fields().names())
    reaches = QgsProject.instance().mapLayersByName("Reaches, generated")
    line = max(reaches[0].getFeatures(), key=lambda f: f.geometry().length()).geometry()
    mid = line.interpolate(line.length() / 2.0).asPoint()
    inflow = h.DATA / "inflow.csv"
    inflow.write_text("minutes,flow\n0,0\n20,40\n60,0\n", encoding="utf-8")
    click("source", mid.x(), mid.y())
    source_fid = max(f.id() for f in layer.getFeatures())
    layer.dataProvider().changeAttributeValues({source_fid: {layer.fields().indexOf("file"): str(inflow)}})
    h.check("no diversion row before a diversion point", box.diversions.isHidden() and not box.diversion_rows)
    click("diversion", mid.x(), mid.y())
    h.check("the table shows the diversion point", len(box.diversion_rows) == 1 and box.diversions.isVisible(),
            box.diversion_rows)  # fmt: skip
    point = box.diversion_rows[0]["name"]
    combo = box.diversions.cellWidget(0, 1)
    offered = [combo.itemText(i) for i in range(combo.count())]
    from wadi2d_qgis.basin_point_rows import DIVERSION_METHODS

    h.check("the five methods are offered", offered[1:] == list(DIVERSION_METHODS), offered)
    combo.setCurrentText("Constant Flow")
    needs = box.diversions.item(0, 6).text()
    h.check("the Needs column follows the method", "rate_m3s" in needs, needs)
    cell(0, 2, reservoir)
    cell(0, 4, json.dumps({"rate_m3s": RATE_M3S}))
    cell(0, 5, json.dumps({"max_volume_m3": VOLUME_M3}))
    feature = next(f for f in layer.getFeatures() if f["name"] == point)
    h.check("the edits are in the layer's fields",
            (feature["method"], feature["divert_to"], json.loads(feature["parameters"]), json.loads(feature["limits"]))
            == ("Constant Flow", reservoir, {"rate_m3s": RATE_M3S}, {"max_volume_m3": VOLUME_M3}),
            [feature[k] for k in ("method", "divert_to", "parameters", "limits")])  # fmt: skip
    h.widget_shot("diversion_table", box)
    bare = yield from generate()
    div = next((e for e in (bare or {"elements": []})["elements"] if e["name"] == point), None)
    h.check("basin.json: the junction carries the read block",
            div is not None and div["diversion"]["method"] == "Constant Flow" and div["diversion"]["divert_to"] == reservoir
            and div["diversion"]["limits"] == {"max_volume_m3": VOLUME_M3}, div and div.get("diversion"))  # fmt: skip
    h.check("the box names the diversion", f"Diversions: {point} (Constant Flow to {reservoir})" in box.summary.text())
    h.check("a source with no area: the box says the area below is the ground's", "no area_km2" in box.summary.text())
    area0 = value(div, "drainage_area_km2") if div else None
    dam0 = value(next(e for e in bare["elements"] if e["name"] == reservoir), "drainage_area_km2") if bare else None

    h.log("=== 2 the source's area")
    layer.dataProvider().changeAttributeValues({source_fid: {layer.fields().indexOf("area_km2"): AREA_KM2}})
    given = yield from generate()
    div2 = next((e for e in (given or {"elements": []})["elements"] if e["name"] == point), None)
    dam2 = value(next(e for e in given["elements"] if e["name"] == reservoir), "drainage_area_km2") if given else None
    h.check("the source's area is in the diversion junction's drainage area",
            div2 is not None and area0 is not None and abs(value(div2, "drainage_area_km2") - area0 - AREA_KM2) < 1e-3,
            (area0, div2 and value(div2, "drainage_area_km2")))  # fmt: skip
    h.check("and in the outlet's", dam0 is not None and dam2 is not None and abs(dam2 - dam0 - AREA_KM2) < 1e-3, (dam0, dam2))
    h.check("the box says so", f"its {AREA_KM2:g} km2 is in the drainage area" in box.summary.text())

    h.log("=== 3 a parameter the method does not take: refused in the engine's words")
    cell(0, 4, json.dumps({"rate": RATE_M3S}))
    refused = yield from generate()
    h.check("refused, the last model kept", refused is None and "takes no ['rate']" in box.summary.text(), box.summary.text()[:300])
    cell(0, 4, json.dumps({"rate_m3s": RATE_M3S}))
    again = yield from generate()
    h.check("mended, generated again", again is not None)

    h.log("=== 4 a run on the generated basin with the diversion")
    folder = h.RUNS / "wiring"
    yield from h.run(dock, 1800)
    done = h.events(folder, "done")
    h.check("the run finished", bool(done) and done[-1].get("code") == 0, dock.panel.message.text()[:300])
    series = folder / "series" / f"network_{point.replace(' ', '_')}.csv"
    rows = list(csv.DictReader(series.open())) if series.is_file() else []
    h.check("the diversion's series", bool(rows) and "diverted_m3s" in rows[0], series.name)
    if rows:
        t = [float(r["t_s"]) for r in rows]
        inflow_s = [float(r["inflow_m3s"]) for r in rows]
        diverted = [float(r["diverted_m3s"]) for r in rows]
        passed = [float(r["passed_m3s"]) for r in rows]
        step = t[1] - t[0]
        volume = sum(diverted) * step
        h.log(f"diversion: inflow peak {max(inflow_s):.2f}, diverted peak {max(diverted):.3f} m3/s, "
              f"diverted volume {volume:.1f} m3, inflow volume {sum(inflow_s) * step:.1f} m3")  # fmt: skip
        h.check("diverted reaches the rate and never passes it", abs(max(diverted) - RATE_M3S) < 1e-6, max(diverted))
        h.check("its volume capped at the limit", abs(volume - VOLUME_M3) < 1e-3 * VOLUME_M3, volume)
        gap = max(abs(i - p - d) for i, p, d in zip(inflow_s, passed, diverted, strict=True))
        h.check("mass closes per ordinate, to the CSV's six digits", gap <= 1e-5 * max(inflow_s), gap)

    h.log("=== 5 a flow line's two columns, and Bidah's pile re-measured")
    box.setChecked(False)
    coords = [o["coordinates"] for o in ground.outlets_data]
    (x0, y0), (x1, y1) = coords[1][0][:2], coords[1][-1][:2]
    middle = [[x0 + 0.25 * (x1 - x0), y0 + 0.25 * (y1 - y0)], [x0 + 0.75 * (x1 - x0), y0 + 0.75 * (y1 - y0)]]
    two = h.add_vector(h.geojson("two", [h.line(coords[0]), h.line(middle)]), "two lines", ground.crs)
    b.layer.setLayer(two)
    b.kind.setCurrentText("free")
    table = b.table
    h.check("the two columns", [table.horizontalHeaderItem(c).text() for c in (4, 5)] == ["Enters moving", "Flows to"])
    moving, side = table.cellWidget(1, 4), table.cellWidget(1, 5)
    h.check("off on a free line", not moving.isEnabled() and not side.isEnabled())
    table.cellWidget(1, 1).setCurrentText("flow")
    h.check("on for a flow line, ticked and auto by default", moving.isEnabled() and moving.isChecked()
            and side.currentData() == "auto")  # fmt: skip
    side.setCurrentIndex(side.findData("right"))
    props = [f.properties for f in b.values(ground.crs)["boundaries"]]
    h.check("a direction chosen reaches the job's line", props[1].get("direction") == "right" and "momentum" not in props[1], props[1])
    side = table.cellWidget(1, 5)  # values() reads the layer again and remakes the cells
    side.setCurrentIndex(side.findData("auto"))
    flow_csv = h.RUNS / "flow.csv"
    flow_csv.write_text("minutes,flow\n0,0\n10,20\n30,20\n40,0\n", encoding="utf-8")
    table.cellWidget(1, 3).setFilePath(str(flow_csv))
    dock.hydrology.rain.setValue(10.0)  # W61's job: 10 mm over half an hour, 1 h, 20 m
    dock.hydrology.hours.setValue(0.5)
    dock.panel.duration.setValue(1.0)
    b.setCollapsed(False)
    h.widget_shot("boundaries_momentum", b)
    measured = {}
    for label, on in (("at rest (W61)", False), ("moving (W70)", True)):
        table.cellWidget(1, 4).setChecked(on)  # the table remakes its cells when the layer is read again
        folder = h.RUNS / ("flow_rest" if not on else "flow_moving")
        dock.panel.folder.setFilePath(str(folder))
        yield from h.run(dock, 1800)
        done = h.events(folder, "done")
        h.check(f"{label}: finished", bool(done) and done[-1].get("code") == 0, dock.panel.message.text()[:300])
        job = json.loads((folder / "job.json").read_text(encoding="utf-8"))["boundaries"][1]["flow"]
        h.check(f"{label}: the job says it", job.get("momentum", True) is on and ("momentum" in job) is (not on), job)
        h.check(f"{label}: direction left to the engine", "direction" not in job, job)
        warns = [e.get("message", "") for e in h.events(folder, "warn") if "domain edge" in e.get("message", "")]
        pile, where = max_depth_near(folder, [PILE], NEAR_M)
        at_line, line_where = max_depth_near(folder, middle, 60.0)
        balance = done[-1]["balance"] if done else {}
        measured[label] = {"pile_m": round(pile, 3), "pile_at": where, "line_max_m": round(at_line, 3),
                           "line_at": line_where, "warning": warns, "inflow_m3": balance.get("inflow_m3"),
                           "relative_error": balance.get("relative_error")}  # fmt: skip
        h.log(f"{label}: {measured[label]}")
    (h.P / "pile.json").write_text(json.dumps(measured, indent=2), encoding="utf-8")
    rest, move = measured.get("at rest (W61)"), measured.get("moving (W70)")
    h.check("W61's pile stands at rest", rest and rest["pile_m"] > 2.0, rest)
    h.check("with momentum the pile is lower", rest and move and move["pile_m"] < rest["pile_m"], (rest, move))

    h.log("=== 6 an HMS basin's reservoirs, read only")
    import importlib

    spec = importlib.util.spec_from_file_location("hms_copy", h.REPO / "W68 layer groups and dock rows" / "hms_copy.py")
    copy = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(copy)
    hms = copy.make(h.P / "hms")
    good = (hms / "Basin_3.basin").read_text(encoding="utf-8")
    h.check("the copy holds an orifice", "Conduit: Orifice" in good)
    (hms / "Basin_bad.basin").write_text(good.replace("Conduit: Orifice", "Conduit: Gated Orifice"), encoding="utf-8")
    hy.folder.setFilePath(str(hms))
    yield lambda: hy.files["basin"].count() > 0
    hy.files["basin"].setCurrentText("Basin_3.basin")
    yield lambda: hy.reservoirs.rowCount() > 0 or "could not" in hy.reservoirs_note.text()
    rows = {hy.reservoirs.item(r, 0).text(): [hy.reservoirs.item(r, c).text() for c in range(4)] for r in range(hy.reservoirs.rowCount())}
    h.log(f"reservoirs: {rows}; {hy.reservoirs_note.text()}")
    bidah = rows.get("Bidah 03 Reservoir")
    h.check("Bidah 03 Reservoir routes as HMS does", bidah and bidah[3] == "routes as HMS does", bidah)
    h.check("its structures as the file holds them", bidah and "Conduit: Orifice" in bidah[2] and "Dam Top" in bidah[2], bidah)
    h.check("the cells are read only", not (hy.reservoirs.item(0, 0).flags() & Qt.ItemIsEditable) or hy.reservoirs.editTriggers() == hy.reservoirs.NoEditTriggers)
    h.widget_shot("reservoirs_table", hy)
    hy.files["basin"].setCurrentText("Basin_bad.basin")
    yield lambda: (hy.reservoirs.rowCount() > 0 and "refused" in " ".join(
        hy.reservoirs.item(r, 3).text() for r in range(hy.reservoirs.rowCount())
    )) or "could not" in hy.reservoirs_note.text()
    words = [hy.reservoirs.item(r, 3).text() for r in range(hy.reservoirs.rowCount())]
    h.log(f"bad: {words}; {hy.reservoirs_note.text()}")
    h.check("the copy the engine refuses: its words", any(w.startswith("refused: ") and "Gated Orifice" in w for w in words), words)
    h.check("the note counts it", "the run stops on the 1 refused" in hy.reservoirs_note.text(), hy.reservoirs_note.text())
